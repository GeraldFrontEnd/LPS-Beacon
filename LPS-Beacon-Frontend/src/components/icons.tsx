import type { ReactNode } from "react";

export interface IconProps {
  size?: number; // width and height in pixels
  className?: string;
}

// Wraps the shapes of one icon in a 24x24 outline SVG. aria-hidden: the button next to it carries the text.
function makeIcon(shapes: ReactNode) {
  return function Icon({ size = 16, className }: IconProps) {
    return (
      <svg
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth="2"
        strokeLinecap="round"
        strokeLinejoin="round"
        className={className}
        aria-hidden="true"
      >
        {shapes}
      </svg>
    );
  };
}

